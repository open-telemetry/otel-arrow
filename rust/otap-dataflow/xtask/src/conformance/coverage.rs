pub const INVENTORY: &str = "rust/otap-dataflow/components-baseline.json";
pub(super) const CATALOG: &str = "rust/otap-dataflow/crates/conformance/fixtures/fixtures.yaml";
const PREREQUISITES: &str = "rust/otap-dataflow/crates/conformance/fixtures/prerequisites.yaml";
// Search the base revision in newest-first order across the driver and format moves.
pub(super) const CATALOG_PATHS: [&str; 4] = [
    CATALOG,
    "rust/otap-dataflow/crates/validation/examples/conformance/fixtures.yaml",
    "rust/otap-dataflow/crates/validation/examples/guarantee_scenarios/fixtures.yaml",
    "rust/otap-dataflow/crates/validation/examples/guarantee_scenarios/fixtures.json",
];
const PREVIOUS_RECORDS: &str = "rust/otap-dataflow/docs/guarantees/coverage.toml";
pub(super) const NO_LIVE_FIXTURE: &str = "No live reconfiguration fixture";
const RECORDS: &str = "rust/otap-dataflow/docs/conformance/coverage.toml";
const SUPPORT: &str = "rust/otap-dataflow/docs/conformance/live-support.md";
const START: &str = "<!-- generated by cargo xtask conformance --write-support -->";
const END: &str = "<!-- end generated coverage -->";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Prerequisite {
    needs: String,
    verify: String,
}

/// Describe the missing environment when a maintainer focuses on one unexercised factory.
pub(super) fn fixture_prerequisite(root: &Path, urn: &str) -> Result<Option<String>> {
    let entries: BTreeMap<String, Prerequisite> =
        serde_yaml::from_slice(&fs::read(root.join(PREREQUISITES))?)?;
    Ok(entries
        .get(urn)
        .map(|entry| format!("{} {}", entry.needs.trim(), entry.verify.trim())))
}

#[derive(Deserialize, Default)]
#[serde(deny_unknown_fields)]
struct Coverage {
    owner: String,
    follow_up: String,
    evidence: BTreeMap<String, Reference>,
    components: BTreeMap<String, BTreeMap<String, String>>,
}
#[derive(Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
struct Reference {
    kind: String,
    source: String,
}

impl Reference {
    fn exercised(
        &self,
        case: &str,
        urn: &str,
        operation: &str,
        observed: &Observations,
    ) -> Result<bool> {
        let passed = observed.checks.get(case) == Some(&true);
        if case == "factory-validation" {
            ensure!(
                operation == "validate startup config",
                "factory validation cannot establish {urn} {operation}"
            );
            return Ok(passed && observed.linked_validators.get(urn) == Some(&true));
        }
        if case == "component-rollout" {
            ensure!(
                Operation::names().contains(&operation),
                "unknown fixture operation {operation}"
            );
            return Ok(observed.linked_validators.contains_key(urn)
                && observed
                    .rollouts
                    .get(urn)
                    .and_then(|r| r.operations.get(operation))
                    == Some(&OperationOutcome::Passed));
        }
        bail!("unknown deployed scenario {case} for {urn} {operation}")
    }
}

#[derive(Deserialize, PartialEq)]
struct Fixture {
    urn: String,
    #[serde(default)]
    requires: BTreeSet<String>,
    #[serde(default)]
    services: BTreeSet<String>,
    probe: serde_json::Value,
    config: serde_json::Value,
    change_config: Option<serde_json::Value>,
}

impl Fixture {
    /// Older catalogs called the pipeline-node probe "graph". A spelling change alone
    /// should not create a new coverage claim for a platform-gated fixture.
    fn normalize_base_probe_kind(&mut self) {
        if let Some(kind) = self.probe.get_mut("kind")
            && kind == "graph"
        {
            *kind = "pipeline-node".into();
        }
    }
}

/// The runtime inventory and enabled prerequisites determine which rows each run must report.
pub(super) fn scheduled_fixtures(root: &Path, report: &Observations) -> Result<BTreeSet<String>> {
    let fixtures: Vec<Fixture> = serde_yaml::from_slice(&fs::read(root.join(CATALOG))?)?;
    Ok(fixtures
        .into_iter()
        .filter(|f| {
            report.linked_validators.contains_key(&f.urn)
                && f.requires.is_subset(&report.prerequisites)
        })
        .map(|f| f.urn)
        .collect())
}

impl Coverage {
    /// A file move alone does not introduce a new claim about deployed behavior.
    fn relocate_base_sources(&mut self) {
        if let Some(reference) = self.evidence.get_mut("component-rollout")
            && let Some(path) = reference.source.strip_prefix("../../")
            && CATALOG_PATHS[1..].contains(&format!("{}/{path}", super::DFE).as_str())
        {
            reference.source = "../../crates/conformance/fixtures/fixtures.yaml".into();
        }
        if let Some(reference) = self.evidence.get_mut("factory-validation")
            && reference.source == "../../crates/validation/tests/common/factory_validators.rs"
        {
            reference.source = "../../crates/validation/src/factory_validators.rs".into();
        }
    }

    /// A declared fixture supplies its three support-table cells, even on another platform.
    fn add_fixtures(&mut self, catalog: &[u8]) -> Result<BTreeMap<String, Fixture>> {
        let mut fixtures = BTreeMap::new();
        for fixture in serde_yaml::from_slice::<Vec<Fixture>>(catalog)? {
            let urn = fixture.urn.clone();
            let ops = self.components.entry(urn.clone()).or_default();
            for op in Operation::names() {
                ensure!(
                    ops.insert(op.to_owned(), "component-rollout".into())
                        .is_none(),
                    "duplicate coverage for {urn} {op}"
                );
            }
            ensure!(
                fixtures.insert(urn.clone(), fixture).is_none(),
                "duplicate live fixture for {urn}"
            );
        }
        Ok(fixtures)
    }
}

pub fn ids(input: &[u8]) -> Result<BTreeMap<String, bool>> {
    registered(serde_json::from_slice(input)?)
}

pub(super) fn registered(entries: Vec<BaselineComponent>) -> Result<BTreeMap<String, bool>> {
    let mut ids = BTreeMap::new();
    for entry in entries {
        if matches!(
            entry.category.as_str(),
            "Receiver" | "Processor" | "Exporter" | "Extension"
        ) {
            ensure!(
                ids.insert(
                    entry.id,
                    entry
                        .attributes
                        .get("scope")
                        .is_some_and(|s| s == "controller")
                )
                .is_none(),
                "duplicate inventory URN"
            );
        }
    }
    Ok(ids)
}

/// New components and previously evidenced operations cannot acquire inherited gaps.
fn needs_evidence(registered_on_base: bool, previously_covered: bool, required: bool) -> bool {
    previously_covered || (required && !registered_on_base)
}

fn components_without_live_fixture<'a>(
    source: &'a BTreeMap<String, bool>,
    fixtures: &BTreeMap<String, Fixture>,
) -> Vec<&'a str> {
    source
        .iter()
        .filter(|(urn, controller)| !**controller && !fixtures.contains_key(*urn))
        .map(|(urn, _)| urn.as_str())
        .collect()
}

fn subject_name(urn: &str) -> String {
    let mut parts = urn.rsplit(':');
    format!(
        "{} {}",
        parts.next().unwrap_or(urn),
        parts.next().unwrap_or_default()
    )
}

#[derive(Serialize)]
pub(super) struct CoverageReport {
    pub registered_operations: usize,
    pub scenario_linked_operations: usize,
    pub exercised_operations: usize,
    pub source_components: Vec<String>,
    /// Fixture outcomes grouped by URN. An empty map means no released configuration is checked.
    pub released_configurations: BTreeMap<String, BTreeMap<String, Option<Outcome>>>,
    pub fixture_gap_reasons: BTreeMap<String, String>,
    pub unlinked_components: Vec<String>,
    pub startup_only: Vec<String>,
    pub linked_validators: BTreeMap<String, bool>,
    pub components_without_live_fixture: Vec<String>,
    pub passing_operations: BTreeMap<String, Vec<String>>,
    pub deferred_fixtures: BTreeMap<String, String>,
    // Keep the individual entries for HTML while preserving the JSON and CLI finding.
    #[serde(skip)]
    pub missing_evidence: Vec<String>,
    pub gap_owner: String,
    pub follow_up: String,
}

pub(super) fn missing_evidence_message(entries: &[String]) -> String {
    format!(
        "Missing component operation evidence: {}",
        entries.join(", ")
    )
}

fn read_base_file(base: &str, paths: &[&str]) -> Result<Option<Vec<u8>>> {
    for path in paths {
        if let Some(data) = read_base(base, path)? {
            return Ok(Some(data));
        }
    }
    Ok(None)
}

pub fn check(
    current: BTreeMap<String, bool>,
    base: Option<&str>,
    write: bool,
    observed: &Observations,
    problems: &mut Vec<String>,
) -> Result<CoverageReport> {
    let linked = &observed.linked_validators;
    let mut records: Coverage = toml::from_str(&fs::read_to_string(RECORDS)?)?;
    let fixtures = records.add_fixtures(&fs::read(CATALOG)?)?;
    for urn in observed.rollouts.keys() {
        ensure!(
            fixtures.contains_key(urn) && linked.contains_key(urn),
            "unexpected live result for {urn}"
        );
    }
    ensure!(
        !records.owner.trim().is_empty() && !records.follow_up.trim().is_empty(),
        "coverage gaps need an owner and follow-up"
    );
    let doc_dir = Path::new(DOCS);
    repository_file(&doc_dir.join(records.follow_up.split('#').next().unwrap_or_default()))?;
    for id in records.components.keys().chain(linked.keys()) {
        ensure!(
            current.contains_key(id),
            "{id} missing from source inventory"
        );
    }
    let prerequisites: BTreeMap<String, Prerequisite> =
        serde_yaml::from_slice(&fs::read(PREREQUISITES)?)?;
    for (urn, entry) in &prerequisites {
        ensure!(
            current.get(urn) == Some(&false) && !fixtures.contains_key(urn),
            "{urn}: obsolete prerequisite record"
        );
        ensure!(
            !entry.needs.trim().is_empty() && !entry.verify.trim().is_empty(),
            "{urn}: provide the environment and acceptance criterion"
        );
    }
    let mut existing = current.clone();
    let mut previous = Coverage::default();
    let mut has_prior_records = false;
    let mut prior_fixtures = BTreeMap::new();
    if let Some(base) = base {
        existing = ids(&read_base(base, INVENTORY)?.context("missing base inventory")?)?;
        if let Some(data) = read_base_file(base, &[RECORDS, PREVIOUS_RECORDS])? {
            has_prior_records = true;
            previous = toml::from_str(std::str::from_utf8(&data)?)?;
            previous.relocate_base_sources();
            if let Some(catalog) = read_base_file(base, &CATALOG_PATHS)? {
                prior_fixtures = previous.add_fixtures(&catalog)?;
                for fixture in prior_fixtures.values_mut() {
                    fixture.normalize_base_probe_kind();
                }
            }
        }
    }
    let mut rows = String::from(
        "| Component | Add | Change | Remove | In-place | Startup validation |\n| --- | --- | --- | --- | --- | --- |\n",
    );
    let mut executable = 0;
    let mut exercised = 0;
    let mut passing_operations: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut total = 0;
    let mut gaps = Vec::new();
    for urn in prior_fixtures
        .keys()
        .filter(|urn| !current.contains_key(*urn))
    {
        gaps.push(format!(
            "{urn}: previously covered component absent from the source inventory"
        ));
    }
    let mut deferred = BTreeMap::new();
    for (id, controller) in &current {
        ensure!(
            !(*controller && fixtures.contains_key(id)),
            "pipeline fixture for controller extension {id}"
        );
        let fixture = fixtures.get(id);
        let scheduled = observed.rollouts.contains_key(id);
        if !write
            && !scheduled
            && linked.contains_key(id)
            && let Some(fixture) = fixture
        {
            let reason = format!(
                "requires {}",
                fixture
                    .requires
                    .difference(&observed.prerequisites)
                    .cloned()
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            let _ = deferred.insert(id.clone(), reason);
        }
        if base.is_some()
            && !controller
            && fixture.is_none()
            && (!existing.contains_key(id) || prior_fixtures.contains_key(id))
        {
            for op in Operation::names() {
                gaps.push(format!("{id} {op}: missing live rollout fixture"));
            }
        }
        let ops = records.components.get(id);
        let required: &[&str] = if *controller {
            &["validate startup config"]
        } else {
            &Operation::names()
        };
        let mut allowed: BTreeSet<_> = required.iter().copied().collect();
        if !*controller {
            allowed.insert("in-place");
        }
        let empty = BTreeMap::new();
        let ops = ops.unwrap_or(&empty);
        ensure!(
            ops.keys().all(|op| allowed.contains(op.as_str())),
            "{id}: unknown operation"
        );
        let old = previous.components.get(id).unwrap_or(&empty);
        write!(rows, "| `{id}` |")?;
        let mut missing_record = *controller && !ops.contains_key("validate startup config");
        for op in Operation::names()
            .into_iter()
            .chain(["in-place", "validate startup config"])
        {
            let prior = old.get(op);
            let cell = if let Some(key) = ops.get(op) {
                let reference = records
                    .evidence
                    .get(key)
                    .with_context(|| format!("{id} {op}: unknown evidence {key}"))?;
                let path = repository_file(
                    &doc_dir.join(reference.source.split('#').next().unwrap_or_default()),
                )?;
                match reference.kind.as_str() {
                    "scenario" => {
                        ensure!(
                            (key == "component-rollout" && path == Path::new(CATALOG))
                                || matches!(
                                    path.extension().and_then(|x| x.to_str()),
                                    Some("rs" | "sh" | "yaml" | "yml")
                                ),
                            "{id} {op}: expected an executable scenario"
                        );
                        let passed = reference.exercised(key, id, op, observed)?;
                        if passed {
                            passing_operations
                                .entry(id.clone())
                                .or_default()
                                .push(op.to_owned());
                        }
                        if required.contains(&op) {
                            executable += 1;
                            exercised += usize::from(passed);
                        }
                        ensure!(
                            key != "component-rollout" || fixture.is_some(),
                            "no fixture for {id}"
                        );
                        let new_claim = (key == "component-rollout"
                            && prior_fixtures.get(id) != fixture)
                            || !existing.contains_key(id)
                            || (has_prior_records
                                && (prior != Some(key)
                                    || previous.evidence.get(key) != Some(reference)));
                        let linked_fixture = key == "component-rollout" && scheduled;
                        if !write && !passed && (linked_fixture || (base.is_some() && new_claim)) {
                            gaps.push(format!("{id} {op}: missing passing {key}"));
                        }
                    }
                    "manual" | "deployment gap" => (),
                    _ => bail!("{id} {op}: unknown evidence kind"),
                }
                let prerequisites = fixture
                    .filter(|_| key == "component-rollout")
                    .map(|f| f.requires.iter().cloned().collect::<Vec<_>>().join(", "))
                    .unwrap_or_default();
                if prerequisites.is_empty() {
                    format!("[{}]({})", reference.kind, reference.source)
                } else {
                    format!(
                        "[{}]({}) (requires {prerequisites})",
                        reference.kind, reference.source
                    )
                }
            } else if required.contains(&op) {
                if needs_evidence(existing.contains_key(id), prior.is_some(), true) {
                    missing_record = true;
                }
                if !*controller && Operation::names().contains(&op) {
                    if !prerequisites.contains_key(id) {
                        gaps.push(format!("{id} {op}: document the missing environment and acceptance criterion in {PREREQUISITES}"));
                    }
                    format!(
                        "[{NO_LIVE_FIXTURE}](#testing-{})",
                        subject_name(id).replace(' ', "-")
                    )
                } else {
                    format!("[untested]({})", records.follow_up)
                }
            } else {
                if needs_evidence(existing.contains_key(id), prior.is_some(), false) {
                    missing_record = true;
                }
                "-".to_owned()
            };
            write!(rows, " {cell} |")?;
        }
        if missing_record {
            gaps.push(id.clone());
        }
        total += required.len();
        rows.push('\n');
    }
    rows.push_str("\n## Environments needed for remaining components\n\nThe Arrow maintainers and component owners track these inherited gaps.\nEach entry gives the setup and the observation needed to add a fixture.\n");
    for (urn, entry) in &prerequisites {
        writeln!(
            rows,
            "\n### Testing {}\n\n{}\n\n{}",
            subject_name(urn),
            entry.needs,
            entry.verify
        )?;
    }
    let doc = fs::read_to_string(SUPPORT)?;
    let (pre, rest) = doc
        .split_once(START)
        .context("missing generated table marker")?;
    let (_, post) = rest
        .split_once(END)
        .context("missing end of generated table")?;
    let rendered = format!("{pre}{START}\n\n{rows}\n{END}{post}");
    if write {
        fs::write(SUPPORT, &rendered)?;
    }
    if !gaps.is_empty() {
        problems.push(missing_evidence_message(&gaps));
    }
    if !write && rendered != doc {
        problems.push("stale support table; run cargo xtask conformance --write-support".into());
    }
    let mut released_configurations: BTreeMap<_, BTreeMap<_, _>> = current
        .keys()
        .map(|urn| (urn.clone(), BTreeMap::new()))
        .collect();
    for (path, urns) in releases::corpus(Path::new(DFE))? {
        for urn in urns {
            let _ = released_configurations
                .entry(urn)
                .or_default()
                .insert(path.clone(), observed.released_inputs.get(&path).cloned());
        }
    }
    Ok(CoverageReport {
        released_configurations,
        registered_operations: total,
        scenario_linked_operations: executable,
        exercised_operations: exercised,
        source_components: current.keys().cloned().collect(),
        fixture_gap_reasons: prerequisites
            .into_iter()
            .map(|(urn, entry)| (urn, entry.needs))
            .collect(),
        unlinked_components: current
            .keys()
            .filter(|urn| !linked.contains_key(*urn))
            .cloned()
            .collect(),
        startup_only: current
            .iter()
            .filter(|(_, controller)| **controller)
            .map(|(urn, _)| urn.clone())
            .collect(),
        linked_validators: linked.clone(),
        passing_operations,
        deferred_fixtures: deferred,
        missing_evidence: gaps,
        components_without_live_fixture: components_without_live_fixture(&current, &fixtures)
            .into_iter()
            .map(str::to_owned)
            .collect(),
        gap_owner: records.owner,
        follow_up: records.follow_up,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Scenario: PR review compares a relocated driver against each historical catalog path.
    /// Guarantees: moves preserve both existing evidence references while a different source stays distinct.
    #[test]
    fn base_evidence_survives_driver_moves() {
        let current: Coverage =
            toml::from_str(include_str!("../../../docs/conformance/coverage.toml")).unwrap();
        for path in &CATALOG_PATHS[1..] {
            let mut base: Coverage =
                toml::from_str(include_str!("../../../docs/conformance/coverage.toml")).unwrap();
            base.evidence.get_mut("component-rollout").unwrap().source = format!(
                "../../{}",
                path.strip_prefix("rust/otap-dataflow/").unwrap()
            );
            base.evidence.get_mut("factory-validation").unwrap().source =
                "../../crates/validation/tests/common/factory_validators.rs".into();
            base.relocate_base_sources();
            assert!(base.evidence == current.evidence);
            base.evidence.get_mut("component-rollout").unwrap().source = "other.yaml".into();
            base.relocate_base_sources();
            assert!(base.evidence != current.evidence);
        }
    }

    /// Scenario: two entries claim coverage for the same component.
    /// Guarantees: conflicting claims fail to deserialize instead of replacing one another.
    #[test]
    fn duplicate_coverage_is_rejected() {
        let records =
            "owner='owners'\nfollow_up='backlog'\n[evidence]\n[components]\nnode={}\nnode={}";
        assert!(toml::from_str::<Coverage>(records).is_err());
    }

    /// Scenario: a component with a reusable probe is added to the fixture catalog.
    /// Guarantees: one entry creates exactly three support claims and cannot overwrite manual evidence.
    #[test]
    fn fixture_declares_all_operations_once() {
        let fixture = b"- urn: example\n  probe: {kind: pipeline-node, role: processor}\n  config: {}\n  requires: [broker]\n";
        let mut coverage = Coverage::default();
        let registered = coverage.add_fixtures(fixture).unwrap();
        assert!(registered["example"].requires.contains("broker"));
        assert_eq!(coverage.components["example"].len(), 3);
        for op in Operation::names() {
            assert_eq!(coverage.components["example"][op], "component-rollout");
        }
        assert!(coverage.add_fixtures(fixture).is_err());
    }

    /// Scenario: a base revision still uses the old "graph" spelling for a pipeline-node probe.
    /// Guarantees: the rename preserves coverage and a changed observation still requires evidence.
    #[test]
    fn base_probe_rename_preserves_only_identical_claims() {
        let fixture = |kind: &str, expect: &str| {
            serde_json::from_value::<Fixture>(serde_json::json!({
                "urn": "urn:otel:processor:attribute",
                "config": {},
                "probe": {"kind": kind, "role": "processor", "expect": {"kind": expect}}
            }))
            .unwrap()
        };
        let mut base = fixture("graph", "marked-log");
        base.normalize_base_probe_kind();
        assert!(base == fixture("pipeline-node", "marked-log"));
        assert!(base != fixture("pipeline-node", "console"));
    }

    /// Scenario: the source inventory includes a platform-only receiver, two catalog fixtures and a controller.
    /// Guarantees: the missing-fixture report identifies the uncovered receiver even before any scenarios run.
    #[test]
    fn missing_live_fixtures_follow_the_source_inventory() {
        let source = BTreeMap::from([
            ("platform_receiver".into(), false),
            ("offline_exporter".into(), false),
            ("broker_extension".into(), false),
            ("controller".into(), true),
        ]);
        let catalog = b"- {urn: offline_exporter, config: {}, probe: {}}\n- {urn: broker_extension, config: {}, probe: {}, requires: [broker]}";
        let fixtures = Coverage::default().add_fixtures(catalog).unwrap();
        assert_eq!(
            components_without_live_fixture(&source, &fixtures),
            ["platform_receiver"]
        );
    }

    /// Scenario: the source inventory contains a platform-gated receiver and a new extension.
    /// Guarantees: both remain discoverable without a runtime factory and the new operation needs evidence.
    #[test]
    fn inventory_covers_unlinked_and_new_factories() {
        let baseline=br#"[{"id":"urn:otel:receiver:etw","category":"Receiver","description":null,"attributes":{}},
                         {"id":"urn:otel:extension:new","category":"Extension","description":null,"attributes":{}}]"#;
        let source = ids(baseline).unwrap();
        assert!(source.contains_key("urn:otel:receiver:etw"));
        assert!(source.contains_key("urn:otel:extension:new"));
        assert!(needs_evidence(false, false, true));
        assert!(needs_evidence(true, true, false));
        assert!(!needs_evidence(true, false, true));
    }
}
