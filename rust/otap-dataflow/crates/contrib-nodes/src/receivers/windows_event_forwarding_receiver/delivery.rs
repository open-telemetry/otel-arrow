//! Single-core event delivery, downstream feedback, and bookmark commit.
//!
//! The future transport must poll deliveries separately from its control loop,
//! route engine Ack/Nack messages here, and call [`Delivery::shutdown`] on stop.
//! No socket, receiver registration, or background task is created here.
//! One deadline covers conversion, output backpressure, and feedback. Expiry or
//! cancellation cannot retract already forwarded records: source retries may
//! duplicate them. Progress is memory-only and sources are never evicted.

use super::{
    bookmark::{BatchOutcome, BookmarkStore, PendingBatch},
    config::{Config, Limits},
    event::{MappingContext, encode_events},
    identity::SourceIdentity,
    wsman::{self, Envelope, Route, messages::Action, messages::bookmark::Bookmark},
};
use otel_arrow_dfe_engine::{
    Interests, MessageSourceLocalEffectHandlerExtension, ProducerEffectHandlerExtension,
    control::{AckMsg, CallData, NackMsg},
    local::receiver::EffectHandler,
};
use otel_arrow_dfe_otap::{
    accessory::slots::{Key, State as Slots},
    pdata::OtapPdata,
};
use std::cell::{Ref, RefCell};
use tokio::{sync::oneshot, time::Instant};
use uuid::Uuid;

/// Delivery failure; none of these results authorizes a SOAP success response.
#[derive(Debug, thiserror::Error)]
pub enum DeliveryError {
    /// Invalid startup configuration.
    #[error("invalid WEF delivery configuration: {0}")]
    Configuration(String),
    /// Invalid route, SOAP request, event wrapper, bookmark, or response size.
    #[error(transparent)]
    Request(#[from] wsman::Error),
    /// Per-source ordering or retained-source/in-flight capacity rejected admission.
    #[error("WEF admission rejected: {0}")]
    Admission(String),
    /// Atomic event conversion failed.
    #[error("WEF conversion failed: {0}")]
    Conversion(String),
    /// Output enqueue failed or downstream rejected the batch, including permanent Nack.
    #[error("WEF downstream delivery failed: {0}")]
    Downstream(String),
    /// The combined enqueue/feedback deadline expired.
    #[error("WEF delivery deadline expired")]
    Timeout,
    /// Ingress has stopped; no further delivery can commit.
    #[error("WEF delivery is shut down")]
    Shutdown,
    /// The completion channel closed without a terminal result.
    #[error("WEF feedback channel closed")]
    FeedbackClosed,
    /// Feedback was not generated by this delivery instance's subscription.
    #[error("invalid WEF feedback correlation")]
    InvalidFeedback,
    /// An internal admission invariant was violated.
    #[error("WEF progress state error: {0}")]
    State(String),
}

/// Authenticated transport metadata for one already bounded and parsed envelope.
pub struct DeliveryContext<'a> {
    /// Source authorized after successful mutual TLS, never an event claim.
    pub source: &'a SourceIdentity,
    /// Transport peer address for the shared Windows event mapping.
    pub peer: &'a str,
    /// Raw HTTP path, used for route and SOAP destination validation.
    pub path: &'a str,
    /// Common observation time for the entire batch.
    pub observed_time_unix_nano: i64,
}

struct Pending {
    batch: PendingBatch,
    deadline: Instant,
    feedback: Option<oneshot::Sender<Result<(), DeliveryError>>>,
}

struct State {
    bookmarks: BookmarkStore,
    pending: Slots<Pending>,
    stopped: bool,
}

/// One subscription's local delivery coordinator.
///
/// Futures borrow this coordinator; RefCell borrows never cross await points.
/// Correlation uses existing generational slots plus a per-instance nonce, so a
/// response from a previous coordinator cannot resolve a recreated slot.
pub struct Delivery {
    subscription_id: Uuid,
    subscription_name: String,
    public_origin: Option<url::Origin>,
    limits: Limits,
    include_event_original: bool,
    instance: (u64, u64),
    state: RefCell<State>,
}

impl Delivery {
    /// Validate startup settings without loading TLS credentials or opening sockets.
    pub fn from_config(config: &Config, receiver_name: &str) -> Result<Self, DeliveryError> {
        config.validate().map_err(DeliveryError::Configuration)?;
        let _ = Instant::now()
            .checked_add(config.limits.feedback_timeout)
            .ok_or_else(|| DeliveryError::Configuration("feedback timeout is too large".into()))?;
        let subscription = &config.subscriptions[0];
        let (subscription_id, _) = subscription
            .identifiers(receiver_name)
            .map_err(|error| DeliveryError::Configuration(error.to_string()))?;
        let public_origin = config
            .public_endpoint
            .as_deref()
            .map(url::Url::parse)
            .transpose()
            .map_err(|error| DeliveryError::Configuration(error.to_string()))?
            .map(|url| url.origin());
        Ok(Self {
            subscription_id,
            subscription_name: subscription.name.clone(),
            public_origin,
            limits: config.limits.clone(),
            include_event_original: config.include_event_original,
            instance: Uuid::new_v4().as_u64_pair(),
            state: RefCell::new(State {
                bookmarks: BookmarkStore::new(subscription_id, &config.limits)
                    .map_err(DeliveryError::Configuration)?,
                pending: Slots::new(config.limits.max_in_flight_batches),
                stopped: false,
            }),
        })
    }

    /// Validate, admit, convert, and deliver a complete Events request.
    ///
    /// The caller bounds and parses the envelope and supplies authorized TLS
    /// identity. This method checks the destination, route, and Identifier itself.
    /// It sends exactly one OTAP batch and subscribes to both Ack and Nack without
    /// retaining a return-data copy. Only wholly validated marker-only batches
    /// bypass downstream. Both paths commit before returning buffered SOAP bytes.
    ///
    /// Dropping this future rejects its admission and preserves the old bookmark.
    /// A timed-out request releases local capacity, not downstream-owned buffers.
    /// Conversion is synchronous and byte/node-bounded; the deadline is checked
    /// afterwards, not a preemption guarantee for parsing or Arrow encoding.
    ///
    /// # Errors
    ///
    /// All failures preserve committed progress and return no success bytes.
    /// Events require AckRequested, so every accepted delivery returns SOAP Ack bytes.
    pub async fn deliver(
        &self,
        envelope: &Envelope<'_>,
        context: &DeliveryContext<'_>,
        effect_handler: &EffectHandler<OtapPdata>,
    ) -> Result<Vec<u8>, DeliveryError> {
        if self.state.borrow().stopped {
            return Err(DeliveryError::Shutdown);
        }
        let deadline = Instant::now()
            .checked_add(self.limits.feedback_timeout)
            .ok_or(DeliveryError::Timeout)?;
        let route = Route::parse(context.path, self.subscription_id)?;
        let Route::Delivery { version } = &route else {
            return Err(wsman::Error::UnsupportedAction.into());
        };
        let request = envelope.request(&route, self.limits.max_request_bytes)?;
        request.validate_destination(self.public_origin.as_ref(), context.path)?;
        if request.action() != Action::Events {
            return Err(wsman::Error::UnsupportedAction.into());
        }
        if request.identifier().and_then(|id| Uuid::parse_str(id).ok())
            != Some(self.subscription_id)
        {
            return Err(wsman::Error::InvalidEnvelope("subscription Identifier mismatch").into());
        }
        // Preflight bounded serialization, but never expose these bytes before commit.
        let response = request.encode_ack(Uuid::new_v4())?;
        let batch = request.event_batch(&self.limits)?;
        let (guard, mut feedback) = self.begin(context.source.clone(), batch.bookmark, deadline)?;
        let records = encode_events(
            &batch.events,
            &MappingContext {
                source: context.source,
                peer: context.peer,
                subscription_name: &self.subscription_name,
                subscription_id: self.subscription_id,
                version,
            },
            &self.limits,
            self.include_event_original,
            context.observed_time_unix_nano,
        )
        .map_err(DeliveryError::Conversion)?;
        drop(batch.events);
        if Instant::now() >= deadline {
            return Err(DeliveryError::Timeout);
        }
        if let Some(records) = records {
            let mut pdata = OtapPdata::new_todo_context(records.into());
            let mut calldata: CallData = guard.key.into();
            calldata.push(self.instance.0.into());
            calldata.push(self.instance.1.into());
            effect_handler.subscribe_to(Interests::ACKS | Interests::NACKS, calldata, &mut pdata);
            let forward = async {
                let sending = effect_handler.send_message_with_source_node(pdata);
                tokio::pin!(sending);
                // A shutdown notification must also interrupt a full output queue.
                tokio::select! {
                    biased;
                    result = &mut feedback => {
                        result.map_err(|_| DeliveryError::FeedbackClosed)??;
                        sending.await.map_err(|error| DeliveryError::Downstream(error.to_string()))
                    }
                    result = &mut sending => {
                        result.map_err(|error| DeliveryError::Downstream(error.to_string()))?;
                        feedback.await.map_err(|_| DeliveryError::FeedbackClosed)?
                    }
                }
            };
            // timeout_at polls its inner future first, which could enqueue after
            // expiry if output capacity becomes ready at the same time.
            tokio::select! {
                biased;
                () = tokio::time::sleep_until(deadline) => return Err(DeliveryError::Timeout),
                result = forward => result?,
            }
        }
        guard.commit()?;
        Ok(response)
    }

    fn begin(
        &self,
        source: SourceIdentity,
        bookmark: Option<Bookmark>,
        deadline: Instant,
    ) -> Result<(Admission<'_>, oneshot::Receiver<Result<(), DeliveryError>>), DeliveryError> {
        let mut state = self.state.borrow_mut();
        if state.stopped {
            return Err(DeliveryError::Shutdown);
        }
        let State {
            bookmarks, pending, ..
        } = &mut *state;
        let slot = pending.reserve().ok_or_else(|| {
            DeliveryError::Admission("maximum in-flight WEF batches reached".into())
        })?;
        let batch = bookmarks
            .begin(source, self.subscription_id, bookmark)
            .map_err(DeliveryError::Admission)?;
        let (sender, receiver) = oneshot::channel();
        let key = slot.insert(Pending {
            batch,
            deadline,
            feedback: Some(sender),
        });
        Ok((
            Admission {
                delivery: self,
                key,
            },
            receiver,
        ))
    }

    /// Route whole-batch engine Ack; this alone does not commit or release admission.
    ///
    /// Returns false for duplicate or expired slots. Invalid/foreign correlation
    /// returns an error, leaving current requests untouched.
    pub fn handle_ack(&self, ack: AckMsg<OtapPdata>) -> Result<bool, DeliveryError> {
        self.feedback(ack.unwind.route.calldata, Ok(()))
    }

    /// Route engine Nack, including permanent rejection, without advancing progress.
    pub fn handle_nack(&self, nack: NackMsg<OtapPdata>) -> Result<bool, DeliveryError> {
        self.feedback(
            nack.unwind.route.calldata,
            Err(DeliveryError::Downstream(nack.reason)),
        )
    }

    fn feedback(
        &self,
        mut calldata: CallData,
        result: Result<(), DeliveryError>,
    ) -> Result<bool, DeliveryError> {
        if calldata.len() != 3
            || u64::from(calldata[1]) != self.instance.0
            || u64::from(calldata[2]) != self.instance.1
        {
            return Err(DeliveryError::InvalidFeedback);
        }
        calldata.truncate(1);
        let key = Key::try_from(calldata).map_err(|_| DeliveryError::InvalidFeedback)?;
        let mut state = self.state.borrow_mut();
        let Some(pending) = state.pending.get_mut(key) else {
            return Ok(false);
        };
        let Some(sender) = pending.feedback.take() else {
            return Ok(false);
        };
        let result = if Instant::now() >= pending.deadline {
            Err(DeliveryError::Timeout)
        } else {
            result
        };
        Ok(sender.send(result).is_ok())
    }

    /// Stop admissions and reject all outstanding requests, including queued Acks.
    ///
    /// The control loop should call this before cancelling/joining transport tasks.
    /// Calls are idempotent. Already committed progress is retained until restart.
    pub fn shutdown(&self) -> Result<(), DeliveryError> {
        let mut state = self.state.borrow_mut();
        state.stopped = true;
        let State {
            bookmarks, pending, ..
        } = &mut *state;
        let mut result = Ok(());
        pending.drain(|pending| {
            if let Err(error) = bookmarks.finish(&pending.batch, BatchOutcome::Nack) {
                result = Err(DeliveryError::State(error));
            }
            if let Some(sender) = pending.feedback {
                // A cancelled caller needs no notification; its admission is already released.
                let _ = sender.send(Err(DeliveryError::Shutdown));
            }
        });
        result
    }

    /// Borrow only committed progress. Drop the borrow before polling any delivery.
    pub fn bookmark(&self, source: &SourceIdentity) -> Option<Ref<'_, Bookmark>> {
        Ref::filter_map(self.state.borrow(), |state| {
            state.bookmarks.bookmark(source)
        })
        .ok()
    }
}

struct Admission<'a> {
    delivery: &'a Delivery,
    key: Key,
}

impl Admission<'_> {
    fn commit(self) -> Result<(), DeliveryError> {
        let mut state = self.delivery.state.borrow_mut();
        let pending = state
            .pending
            .take(self.key)
            .ok_or(DeliveryError::Shutdown)?;
        let expired = Instant::now() >= pending.deadline;
        state
            .bookmarks
            .finish(
                &pending.batch,
                if expired {
                    BatchOutcome::Nack
                } else {
                    BatchOutcome::Ack
                },
            )
            .map_err(DeliveryError::State)?;
        if expired {
            Err(DeliveryError::Timeout)
        } else {
            Ok(())
        }
    }
}

impl Drop for Admission<'_> {
    fn drop(&mut self) {
        let mut state = self.delivery.state.borrow_mut();
        if let Some(pending) = state.pending.take(self.key)
            && let Err(error) = state.bookmarks.finish(&pending.batch, BatchOutcome::Nack)
        {
            otel_arrow_dfe_telemetry::otel_error!("wef.delivery.cleanup.failed", error = %error);
        }
    }
}

